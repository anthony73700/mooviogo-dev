def write_catalog(lang: str, msgids: list[str]) -> None:
    po_path = LOCALE_DIR / lang / "LC_MESSAGES" / "django.po"
    mo_path = LOCALE_DIR / lang / "LC_MESSAGES" / "django.mo"
    po_path.parent.mkdir(parents=True, exist_ok=True)

    po = polib.POFile()
    po.metadata = {
        "Project-Id-Version": "mooviogo",
        "Report-Msgid-Bugs-To": "",
        "POT-Creation-Date": "2026-05-15 00:00+0000",
        "PO-Revision-Date": "2026-05-15 00:00+0000",
        "Last-Translator": "GitHub Copilot",
        "Language-Team": "",
        "Language": lang,
        "MIME-Version": "1.0",
        "Content-Type": "text/plain; charset=UTF-8",
        "Content-Transfer-Encoding": "8bit",
        "Plural-Forms": (
            "nplurals=2; plural=(n > 1);"
            if lang == "fr"
            else "nplurals=2; plural=(n != 1);"
        ),
    }

    for msgid in msgids:
        if lang == "fr":
            msgstr = build_fr_translation(msgid)
        elif lang == "en":
            msgstr = build_en_translation(msgid)
        else:
            msgstr = build_es_translation(msgid)
        po.append(polib.POEntry(msgid=msgid, msgstr=msgstr))

    po.save(po_path)
    po.save_as_mofile(mo_path)


def main() -> None:
    msgids = collect_msgids()
    write_catalog("fr", msgids)
    write_catalog("en", msgids)
    write_catalog("es", msgids)
    print(f"Generated catalogs for {len(msgids)} msgids (fr, en, es)")


